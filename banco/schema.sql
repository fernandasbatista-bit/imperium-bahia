-- MySQL 8.0.16+; esquema da integração demonstrativa.
CREATE DATABASE IF NOT EXISTS imperium_bahia CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE imperium_bahia;
CREATE TABLE IF NOT EXISTS cliente (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nome VARCHAR(120) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE,
 senha_hash VARCHAR(255) NOT NULL,
 criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS categoria (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(80) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS marca (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(80) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS produto (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 categoria_id INT UNSIGNED NOT NULL,
 marca_id INT UNSIGNED NOT NULL,
 nome VARCHAR(180) NOT NULL,
 descricao TEXT NOT NULL,
 preco DECIMAL(10,2) NOT NULL CHECK(preco >= 0),
 imagem VARCHAR(500),
 ativo BOOLEAN NOT NULL DEFAULT TRUE,
 FOREIGN KEY(categoria_id) REFERENCES categoria(id), FOREIGN KEY(marca_id) REFERENCES marca(id)
);
CREATE TABLE IF NOT EXISTS variante (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 produto_id INT UNSIGNED NOT NULL,
 sku VARCHAR(80) NOT NULL UNIQUE,
 tamanho VARCHAR(16) NOT NULL,
 cor VARCHAR(60) NOT NULL,
 estoque INT UNSIGNED NOT NULL DEFAULT 0,
 UNIQUE(produto_id,tamanho,cor), FOREIGN KEY(produto_id) REFERENCES produto(id)
);
CREATE TABLE IF NOT EXISTS pedido (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 cliente_id INT UNSIGNED NOT NULL,
 subtotal DECIMAL(10,2) NOT NULL CHECK(subtotal >= 0),
 desconto DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK(desconto >= 0),
 frete DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK(frete >= 0),
 total DECIMAL(10,2) NOT NULL CHECK(total >= 0),
 cupom VARCHAR(32), status VARCHAR(24) NOT NULL DEFAULT 'demonstrativo',
 criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(desconto <= subtotal AND total = subtotal - desconto + frete),
 FOREIGN KEY(cliente_id) REFERENCES cliente(id)
);
CREATE TABLE IF NOT EXISTS item_pedido (
 pedido_id INT UNSIGNED NOT NULL, variante_id INT UNSIGNED NOT NULL,
 quantidade INT UNSIGNED NOT NULL CHECK(quantidade > 0), preco_unitario DECIMAL(10,2) NOT NULL CHECK(preco_unitario >= 0),
 PRIMARY KEY(pedido_id,variante_id), FOREIGN KEY(pedido_id) REFERENCES pedido(id), FOREIGN KEY(variante_id) REFERENCES variante(id)
);
CREATE TABLE IF NOT EXISTS interacao_chatbot (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 cliente_id INT UNSIGNED NULL, sessao VARCHAR(64) NOT NULL,
 pergunta VARCHAR(500) NOT NULL, resposta TEXT NOT NULL,
 modo VARCHAR(24) NOT NULL, criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(cliente_id) REFERENCES cliente(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS recomendacao (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 interacao_id INT UNSIGNED NOT NULL, produto_id INT UNSIGNED NOT NULL,
 posicao INT UNSIGNED NOT NULL CHECK(posicao > 0), pontuacao DECIMAL(8,4) NULL,
 UNIQUE(interacao_id,produto_id), UNIQUE(interacao_id,posicao),
 FOREIGN KEY(interacao_id) REFERENCES interacao_chatbot(id), FOREIGN KEY(produto_id) REFERENCES produto(id)
);
CREATE TABLE IF NOT EXISTS avaliacao (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 pedido_id INT UNSIGNED NOT NULL UNIQUE,
 estrelas TINYINT UNSIGNED NOT NULL CHECK(estrelas BETWEEN 1 AND 5),
 observacoes TEXT NULL, criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(pedido_id) REFERENCES pedido(id)
);
